/**
 * Gentle Rain — soft rainfall with an unhurried piano over it. The bed is
 * darker and quieter than plain rain noise so the notes have room; the piano
 * plays a pentatonic scale, where no two notes can clash, at intervals long
 * enough that it never becomes a melody to follow.
 */
const RAIN_PIANO_SCALE = ['F3', 'A3', 'C4', 'D4', 'F4', 'G4', 'A4', 'C5', 'D5', 'F5']

const gentleRain = (ctx) => {
  const src = loopingSource(ctx, createPinkNoiseBuffer(ctx))

  const body = ctx.createBiquadFilter()
  body.type = 'bandpass'
  body.frequency.value = 640
  body.Q.value = 0.5

  // Takes the hiss off the top of the bed — rain heard through glass.
  const muffle = ctx.createBiquadFilter()
  muffle.type = 'lowpass'
  muffle.frequency.value = 2400
  muffle.Q.value = 0.3

  const airSrc = loopingSource(ctx, createWhiteNoiseBuffer(ctx))
  const air = ctx.createBiquadFilter()
  air.type = 'highpass'
  air.frequency.value = 5200
  const airGain = ctx.createGain()
  airGain.gain.value = 0.02

  const rainGain = ctx.createGain()
  rainGain.gain.value = 0.62

  const out = ctx.createGain()
  out.gain.value = 0.9

  src.connect(body).connect(muffle).connect(rainGain).connect(out)
  airSrc.connect(air).connect(airGain).connect(rainGain)

  const reverb = createReverb(ctx, { seconds: 3.4, decay: 2.6, wet: 0.5 })
  reverb.output.connect(out)

  const piano = ctx.createGain()
  piano.gain.value = 0.9
  piano.connect(out)

  // Rain intensity gently swells and recedes.
  const lfo = slowLfo(ctx, { rate: 0.05, depth: 240, offset: 640, target: body.frequency })

  let lastIndex = -1
  const notes = noteScheduler(ctx, {
    delay: 1.6,
    tick: (at) => {
      // Never repeat the previous note; small steps are more common than leaps.
      let index = lastIndex
      while (index === lastIndex) {
        const drift = Math.floor(Math.random() * 5) - 2
        index =
          lastIndex < 0
            ? Math.floor(Math.random() * RAIN_PIANO_SCALE.length)
            : Math.min(RAIN_PIANO_SCALE.length - 1, Math.max(0, lastIndex + drift))
      }
      lastIndex = index

      const frequency = noteFreq(RAIN_PIANO_SCALE[index])
      pianoNote(ctx, {
        frequency,
        at,
        velocity: 0.16 + Math.random() * 0.1,
        decay: 6,
        destination: piano,
        send: reverb.input,
      })

      // Sometimes a quieter note answers it a beat later.
      if (Math.random() < 0.4) {
        const partner = Math.min(RAIN_PIANO_SCALE.length - 1, index + 2)
        pianoNote(ctx, {
          frequency: noteFreq(RAIN_PIANO_SCALE[partner]),
          at: at + 0.55 + Math.random() * 0.35,
          velocity: 0.09 + Math.random() * 0.05,
          decay: 5,
          destination: piano,
          send: reverb.input,
        })
      }

      return 4.5 + Math.random() * 4
    },
  })

  return {
    output: out,
    start: () => {
      src.start()
      airSrc.start()
      lfo.osc.start()
      notes.start()
    },
    stop: () => {
      src.stop()
      airSrc.stop()
      lfo.osc.stop()
      notes.stop()
    },
  }
}

/** Ocean Brown Noise — brown noise swelling like slow surf. */
const oceanBrownNoise = (ctx) => {
  const src = loopingSource(ctx, createBrownNoiseBuffer(ctx))

  const tone = ctx.createBiquadFilter()
  tone.type = 'lowpass'
  tone.frequency.value = 620
  tone.Q.value = 0.4

  const swell = ctx.createGain()
  swell.gain.value = 0.5

  const out = ctx.createGain()
  out.gain.value = 1

  src.connect(tone).connect(swell).connect(out)

  // ~11s wave period.
  const waves = slowLfo(ctx, { rate: 0.09, depth: 0.32, offset: 0.55, target: swell.gain })
  const brightness = slowLfo(ctx, { rate: 0.045, depth: 180, offset: 620, target: tone.frequency })

  return {
    output: out,
    start: () => { src.start(); waves.osc.start(); brightness.osc.start() },
    stop: () => { src.stop(); waves.osc.stop(); brightness.osc.stop() },
  }
}

/** Forest Wind — filtered white noise drifting through imaginary leaves. */
const forestWind = (ctx) => {
  const src = loopingSource(ctx, createWhiteNoiseBuffer(ctx))

  const gust = ctx.createBiquadFilter()
  gust.type = 'bandpass'
  gust.frequency.value = 520
  gust.Q.value = 1.6

  const leaves = loopingSource(ctx, createPinkNoiseBuffer(ctx))
  const leafFilter = ctx.createBiquadFilter()
  leafFilter.type = 'highpass'
  leafFilter.frequency.value = 2600
  const leafGain = ctx.createGain()
  leafGain.gain.value = 0.05

  const breath = ctx.createGain()
  breath.gain.value = 0.6

  const out = ctx.createGain()
  out.gain.value = 1

  src.connect(gust).connect(breath).connect(out)
  leaves.connect(leafFilter).connect(leafGain).connect(out)

  const sweep = slowLfo(ctx, { rate: 0.07, depth: 340, offset: 560, target: gust.frequency })
  const gusting = slowLfo(ctx, { rate: 0.033, depth: 0.3, offset: 0.55, target: breath.gain })
  const rustle = slowLfo(ctx, { rate: 0.12, depth: 0.035, offset: 0.05, target: leafGain.gain })

  return {
    output: out,
    start: () => {
      src.start(); leaves.start()
      sweep.osc.start(); gusting.osc.start(); rustle.osc.start()
    },
    stop: () => {
      src.stop(); leaves.stop()
      sweep.osc.stop(); gusting.osc.stop(); rustle.osc.stop()
    },
  }
}

/**
 * Soft Hum — a warm drone with a gentle 6 Hz binaural offset between ears,
 * layered over a whisper of noise so it never feels sterile.
 */
const softHum = (ctx) => {
  const baseFreq = 136.1 // "Om" / C#, a classic meditation tone
  const beat = 6 // theta-range binaural offset

  const merger = ctx.createChannelMerger(2)

  const left = ctx.createOscillator()
  left.type = 'sine'
  left.frequency.value = baseFreq

  const right = ctx.createOscillator()
  right.type = 'sine'
  right.frequency.value = baseFreq + beat

  const leftGain = ctx.createGain()
  const rightGain = ctx.createGain()
  leftGain.gain.value = 0.5
  rightGain.gain.value = 0.5

  left.connect(leftGain).connect(merger, 0, 0)
  right.connect(rightGain).connect(merger, 0, 1)

  // A fifth above, quietly, for warmth.
  const fifth = ctx.createOscillator()
  fifth.type = 'sine'
  fifth.frequency.value = baseFreq * 1.5
  const fifthGain = ctx.createGain()
  fifthGain.gain.value = 0.08

  // Whisper bed so the drone sits in a space.
  const bed = loopingSource(ctx, createBrownNoiseBuffer(ctx))
  const bedFilter = ctx.createBiquadFilter()
  bedFilter.type = 'lowpass'
  bedFilter.frequency.value = 320
  const bedGain = ctx.createGain()
  bedGain.gain.value = 0.12

  const warmth = ctx.createBiquadFilter()
  warmth.type = 'lowpass'
  warmth.frequency.value = 900

  const out = ctx.createGain()
  out.gain.value = 0.85

  merger.connect(warmth).connect(out)
  fifth.connect(fifthGain).connect(out)
  bed.connect(bedFilter).connect(bedGain).connect(out)

  const drift = slowLfo(ctx, { rate: 0.04, depth: 0.16, offset: 0.7, target: out.gain })

  return {
    output: out,
    start: () => { left.start(); right.start(); fifth.start(); bed.start(); drift.osc.start() },
    stop: () => { left.stop(); right.stop(); fifth.stop(); bed.stop(); drift.osc.stop() },
  }
}

/**
 * Classic Strings — a slow canon in D for string section, piano and a plucked
 * upper voice, over the eight-chord ground bass that most of the calm
 * classical repertoire is built on. Each bar re-voices itself slightly, so it
 * repeats without landing in exactly the same place twice.
 */
const CANON_PROGRESSION = [
  { pad: ['D3', 'A3', 'D4', 'F#4'], arp: ['D4', 'F#4', 'A4', 'D5', 'A4'] },
  { pad: ['A2', 'E3', 'A3', 'C#4'], arp: ['A3', 'C#4', 'E4', 'A4', 'E4'] },
  { pad: ['B2', 'F#3', 'B3', 'D4'], arp: ['B3', 'D4', 'F#4', 'B4', 'F#4'] },
  { pad: ['F#2', 'C#3', 'F#3', 'A3'], arp: ['F#3', 'A3', 'C#4', 'F#4', 'C#4'] },
  { pad: ['G2', 'D3', 'G3', 'B3'], arp: ['G3', 'B3', 'D4', 'G4', 'D4'] },
  { pad: ['D3', 'A3', 'D4', 'F#4'], arp: ['D4', 'F#4', 'A4', 'D5', 'F#4'] },
  { pad: ['G2', 'D3', 'G3', 'B3'], arp: ['G3', 'D4', 'G4', 'B4', 'G4'] },
  { pad: ['A2', 'E3', 'A3', 'C#4'], arp: ['A3', 'E4', 'A4', 'C#5', 'A4'] },
]

const CANON_BAR = 7.6

const classicStrings = (ctx) => {
  const out = ctx.createGain()
  out.gain.value = 0.9

  const reverb = createReverb(ctx, { seconds: 4, decay: 2.4, wet: 0.55 })
  reverb.output.connect(out)

  const strings = ctx.createGain()
  strings.gain.value = 0.85
  strings.connect(out)

  const keys = ctx.createGain()
  keys.gain.value = 0.7
  keys.connect(out)

  // Air around the section — a concert hall is never silent.
  const room = loopingSource(ctx, createPinkNoiseBuffer(ctx))
  const roomFilter = ctx.createBiquadFilter()
  roomFilter.type = 'lowpass'
  roomFilter.frequency.value = 900
  const roomGain = ctx.createGain()
  roomGain.gain.value = 0.035
  room.connect(roomFilter).connect(roomGain).connect(out)

  let bar = 0
  const notes = noteScheduler(ctx, {
    delay: 0.1,
    tick: (at) => {
      const { pad, arp } = CANON_PROGRESSION[bar % CANON_PROGRESSION.length]

      stringChord(ctx, {
        frequencies: pad.map(noteFreq),
        at,
        duration: CANON_BAR * 0.72,
        level: 0.13,
        attack: 2.4,
        release: 3.2,
        destination: strings,
        send: reverb.input,
      })

      // The upper line enters on the second pass and then stays.
      if (bar > 0) {
        arp.forEach((name, index) => {
          pianoNote(ctx, {
            frequency: noteFreq(name),
            at: at + 0.35 + index * 0.95,
            velocity: (index === 0 ? 0.17 : 0.12) - Math.random() * 0.03,
            decay: 5.5,
            destination: keys,
            send: reverb.input,
          })
        })
      }

      bar++
      return CANON_BAR
    },
  })

  // The section breathes across the whole progression, not bar by bar.
  const swell = slowLfo(ctx, { rate: 0.016, depth: 0.14, offset: 0.82, target: out.gain })

  return {
    output: out,
    start: () => {
      room.start()
      swell.osc.start()
      notes.start()
    },
    stop: () => {
      room.stop()
      swell.osc.stop()
      notes.stop()
    },
  }
}

