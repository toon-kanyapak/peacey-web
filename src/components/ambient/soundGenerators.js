const SEMITONES = { C: 0, D: 2, E: 4, F: 5, G: 7, A: 9, B: 11 }

/** 'F#3' | 'Bb4' | 'A3' -> frequency in Hz (A4 = 440). */
const noteFreq = (name) => {
  const [, letter, accidental, octave] = /^([A-G])([#b]?)(-?\d)$/.exec(name)
  const semitone = SEMITONES[letter] + (accidental === '#' ? 1 : accidental === 'b' ? -1 : 0)
  const midi = (Number(octave) + 1) * 12 + semitone
  return 440 * 2 ** ((midi - 69) / 12)
}

/**
 * Impulse response for a small, soft room: decaying noise. The tail is most
 * of what makes a pitched voice read as "played in a room" rather than
 * "generated by an oscillator".
 */
const createImpulseResponse = (ctx, { seconds = 2.8, decay = 3.2 } = {}) => {
  const length = Math.floor(ctx.sampleRate * seconds)
  const buffer = ctx.createBuffer(2, length, ctx.sampleRate)
  for (let channel = 0; channel < 2; channel++) {
    const data = buffer.getChannelData(channel)
    for (let i = 0; i < length; i++) {
      data[i] = (Math.random() * 2 - 1) * (1 - i / length) ** decay
    }
  }
  return buffer
}

/** A reverb send: play notes into `input`, patch `output` into the mix. */
const createReverb = (ctx, { seconds, decay, wet = 0.3 } = {}) => {
  const input = ctx.createGain()
  const convolver = ctx.createConvolver()
  convolver.buffer = createImpulseResponse(ctx, { seconds, decay })
  const damp = ctx.createBiquadFilter()
  damp.type = 'lowpass'
  damp.frequency.value = 2600
  const output = ctx.createGain()
  output.gain.value = wet
  input.connect(convolver).connect(damp).connect(output)
  return { input, output }
}

/**
 * A felt-piano note: sine partials with their own decay rates under a lowpass
 * that closes as the note rings out — a struck string loses its brightness
 * well before it loses its volume.
 */
const pianoNote = (ctx, { frequency, at, velocity = 0.4, decay = 5, destination, send }) => {
  const now = Math.max(at, ctx.currentTime)

  const tone = ctx.createBiquadFilter()
  tone.type = 'lowpass'
  tone.Q.value = 0.35
  tone.frequency.setValueAtTime(Math.min(frequency * 8, 5400), now)
  tone.frequency.exponentialRampToValueAtTime(Math.max(frequency * 2, 260), now + decay * 0.75)

  const env = ctx.createGain()
  env.gain.setValueAtTime(0.0001, now)
  env.gain.exponentialRampToValueAtTime(velocity, now + 0.014)
  env.gain.exponentialRampToValueAtTime(0.0001, now + decay)

  // [ratio, level, share of the total decay]
  const partials = [
    [1, 1, 1],
    [2, 0.3, 0.62],
    [3.01, 0.12, 0.42],
    [4.02, 0.05, 0.28],
  ]

  const oscs = partials.map(([ratio, level, life]) => {
    const osc = ctx.createOscillator()
    osc.type = 'sine'
    osc.frequency.value = frequency * ratio
    const gain = ctx.createGain()
    gain.gain.setValueAtTime(level, now)
    gain.gain.exponentialRampToValueAtTime(0.0001, now + decay * life)
    osc.connect(gain).connect(tone)
    osc.start(now)
    osc.stop(now + decay + 0.2)
    return osc
  })

  tone.connect(env)
  env.connect(destination)
  if (send) env.connect(send)

  oscs[0].onended = () => {
    try {
      env.disconnect()
      tone.disconnect()
    } catch {
      /* already torn down */
    }
  }
}

/**
 * A bowed chord: detuned saw pairs per note, opened and closed slowly enough
 * that consecutive chords overlap into one another instead of stepping.
 */
const stringChord = (
  ctx,
  { frequencies, at, duration = 7, level = 0.14, attack = 2.2, release = 3, destination, send },
) => {
  const now = Math.max(at, ctx.currentTime)

  const body = ctx.createBiquadFilter()
  body.type = 'lowpass'
  body.Q.value = 0.5
  body.frequency.setValueAtTime(900, now)
  body.frequency.linearRampToValueAtTime(1500, now + attack)
  body.frequency.linearRampToValueAtTime(820, now + duration + release)

  const env = ctx.createGain()
  env.gain.setValueAtTime(0.0001, now)
  env.gain.linearRampToValueAtTime(level, now + attack)
  env.gain.setValueAtTime(level, now + duration)
  env.gain.exponentialRampToValueAtTime(0.0001, now + duration + release)

  const oscs = []
  frequencies.forEach((frequency, index) => {
    // Quieter towards the top of the voicing, the way a section balances itself.
    const weight = 1 / (1 + index * 0.35)
    ;[-4, 4].forEach((detune) => {
      const osc = ctx.createOscillator()
      osc.type = 'sawtooth'
      osc.frequency.value = frequency
      osc.detune.value = detune
      const gain = ctx.createGain()
      gain.gain.value = 0.16 * weight
      osc.connect(gain).connect(body)
      osc.start(now)
      osc.stop(now + duration + release + 0.2)
      oscs.push(osc)
    })
  })

  body.connect(env)
  env.connect(destination)
  if (send) env.connect(send)

  oscs[0].onended = () => {
    try {
      env.disconnect()
      body.disconnect()
    } catch {
      /* already torn down */
    }
  }
}

/**
 * Note scheduler. `tick(at)` schedules whatever should sound at `at` and
 * returns the seconds to wait before the next call, so a generator can play
 * in strict time (a progression) or loosely (rain piano).
 */
const noteScheduler = (ctx, { delay = 0.1, tick }) => {
  let timer = null
  let stopped = false

  const run = () => {
    if (stopped) return
    const gap = tick(ctx.currentTime + 0.08)
    timer = window.setTimeout(run, gap * 1000)
  }

  return {
    start: () => {
      timer = window.setTimeout(run, delay * 1000)
    },
    stop: () => {
      stopped = true
      if (timer !== null) window.clearTimeout(timer)
      timer = null
    },
  }
}

